export function getCategoryById(categoryId: string | null | undefined): Category | null {
  if (!categoryId) return null;
  return initialCategories.find((cat) => cat.id === String(categoryId)) || null;
}

export function getCategoryName(categoryId: string | null | undefined): string {
  const cat = getCategoryById(categoryId);
  return cat ? cat.name : "";
}

